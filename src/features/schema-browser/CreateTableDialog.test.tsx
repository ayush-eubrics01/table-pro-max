import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { cleanup, fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import { clearMocks, mockIPC } from "@tauri-apps/api/mocks";
import type { ColumnDef, SessionInfo } from "../../types/backend";
import { session } from "../../test/fixtures";
import { Overlays } from "../../components/Overlays";
import { useUi } from "../../stores/ui";
import { CreateTableDialog } from "./CreateTableDialog";

const STATEMENTS = ['CREATE TABLE "public"."orders" (\n  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n  "total" numeric(12,2)\n)'];

let previews: { sessionId: string; request: { schema: string; name: string; columns: ColumnDef[] } }[] = [];
let ddl: { sessionId: string; statements: string[] }[] = [];
let previewError: unknown = null;
let applyError: unknown = null;

beforeEach(() => {
  previews = [];
  ddl = [];
  previewError = null;
  applyError = null;
  useUi.setState({ toasts: [], confirmRequest: null });
  mockIPC((cmd, args) => {
    const a = args as Record<string, unknown>;
    switch (cmd) {
      case "preview_create_table":
        if (previewError) throw previewError;
        previews.push(a as (typeof previews)[number]);
        return STATEMENTS;
      case "apply_ddl":
        ddl.push({ sessionId: a.sessionId as string, statements: a.statements as string[] });
        if (applyError) throw applyError;
        return null;
      default:
        return null;
    }
  });
});

afterEach(() => {
  cleanup();
  clearMocks();
});

function renderDialog(s: SessionInfo = session) {
  const onClose = vi.fn();
  const onCreated = vi.fn();
  render(
    <>
      <CreateTableDialog session={s} schema="public" onClose={onClose} onCreated={onCreated} />
      <Overlays />
    </>,
  );
  const dialog = screen.getByRole("dialog", { name: "New table in public" });
  return { onClose, onCreated, dialog: within(dialog) };
}

const names = () => screen.getAllByLabelText("Column name");
const reviewButton = () => screen.getByRole("button", { name: "Review SQL" });

async function openReview() {
  fireEvent.click(reviewButton());
  return screen.findByRole("dialog", { name: "Create table" });
}

describe("CreateTableDialog", () => {
  it.each([
    ["postgres", "PostgreSQL", "bigint GENERATED BY DEFAULT AS IDENTITY", "text"],
    ["mysql", "MySQL", "bigint AUTO_INCREMENT", "varchar(255)"],
    ["mssql", "Microsoft SQL Server", "bigint IDENTITY", "nvarchar(255)"],
    ["sqlite", "SQLite", "INTEGER", "REAL"],
    ["postgres", "DuckDB", "BIGINT", "text"],
  ] as const)("starts %s (%s) with an id key column typed for it and suggests its types", (dialect, product, idType, nextType) => {
    renderDialog({ ...session, dialect, server: { ...session.server, product } });
    expect(names()).toHaveLength(1);
    expect(names()[0]).toHaveValue("id");
    expect(screen.getByLabelText("Type")).toHaveValue(idType);
    expect(screen.getByLabelText("Primary key")).toBeChecked();
    expect(screen.getByLabelText("Nullable")).not.toBeChecked();

    fireEvent.click(screen.getByRole("button", { name: /Add column/ }));
    expect(names()).toHaveLength(2);
    expect(screen.getAllByLabelText("Type")[1]).toHaveValue(nextType);
    expect(screen.getAllByLabelText("Nullable")[1]).toBeChecked();
    expect(screen.getAllByLabelText("Primary key")[1]).not.toBeChecked();
  });

  it("enables Review SQL only once the table and every column have a name", () => {
    renderDialog();
    expect(reviewButton()).toBeDisabled();
    fireEvent.change(screen.getByLabelText("Table name"), { target: { value: "   " } });
    expect(reviewButton()).toBeDisabled();
    fireEvent.change(screen.getByLabelText("Table name"), { target: { value: "orders" } });
    expect(reviewButton()).toBeEnabled();

    fireEvent.click(screen.getByRole("button", { name: /Add column/ }));
    expect(reviewButton()).toBeDisabled();
    fireEvent.change(names()[1]!, { target: { value: "total" } });
    expect(reviewButton()).toBeEnabled();
    fireEvent.change(names()[0]!, { target: { value: "" } });
    expect(reviewButton()).toBeDisabled();
  });

  it("keeps at least one column and removes the one asked for", () => {
    renderDialog();
    const removes = () => screen.getAllByRole("button", { name: "Remove column" });
    expect(removes()[0]).toBeDisabled();

    fireEvent.click(screen.getByRole("button", { name: /Add column/ }));
    fireEvent.change(names()[1]!, { target: { value: "total" } });
    expect(removes()[0]).toBeEnabled();
    fireEvent.click(removes()[0]!);
    expect(names().map((n) => (n as HTMLInputElement).value)).toEqual(["total"]);
    expect(removes()[0]).toBeDisabled();
  });

  it("makes a primary key column NOT NULL", () => {
    renderDialog();
    fireEvent.click(screen.getByRole("button", { name: /Add column/ }));
    const nullable = screen.getAllByLabelText("Nullable")[1]!;
    const key = screen.getAllByLabelText("Primary key")[1]!;
    expect(nullable).toBeChecked();
    fireEvent.click(key);
    expect(key).toBeChecked();
    expect(nullable).not.toBeChecked();
    fireEvent.click(key);
    expect(key).not.toBeChecked();
    expect(nullable).not.toBeChecked();
  });

  it("previews the CREATE TABLE for the columns entered, then creates it", async () => {
    const { onCreated, onClose } = renderDialog();
    fireEvent.change(screen.getByLabelText("Table name"), { target: { value: "  orders " } });
    fireEvent.click(screen.getByRole("button", { name: /Add column/ }));
    fireEvent.change(names()[1]!, { target: { value: "total" } });
    fireEvent.change(screen.getAllByLabelText("Type")[1]!, { target: { value: "numeric(12,2)" } });
    fireEvent.change(screen.getAllByLabelText("Default")[1]!, { target: { value: "0" } });
    fireEvent.click(screen.getAllByLabelText("Nullable")[1]!);

    const review = await openReview();
    expect(previews).toEqual([
      {
        sessionId: "sess-1",
        request: {
          schema: "public",
          name: "orders",
          columns: [
            { name: "id", dataType: "bigint GENERATED BY DEFAULT AS IDENTITY", nullable: false, default: null, primaryKey: true },
            { name: "total", dataType: "numeric(12,2)", nullable: false, default: "0", primaryKey: false },
          ],
        },
      },
    ]);
    expect(review).toHaveTextContent('CREATE TABLE "public"."orders"');
    expect(review).toHaveTextContent("one transaction");
    expect(ddl).toEqual([]);

    fireEvent.click(within(review).getByRole("button", { name: "Create table" }));
    await waitFor(() => expect(onCreated).toHaveBeenCalledWith("orders"));
    expect(ddl).toEqual([{ sessionId: "sess-1", statements: STATEMENTS }]);
    expect(screen.getByRole("status")).toHaveTextContent(/Created\s+orders/);
    expect(onClose).not.toHaveBeenCalled();
  });

  it("clears a typed default back to none", async () => {
    renderDialog();
    fireEvent.change(screen.getByLabelText("Table name"), { target: { value: "orders" } });
    const def = screen.getByLabelText("Default");
    fireEvent.change(def, { target: { value: "1" } });
    fireEvent.change(def, { target: { value: "" } });
    await openReview();
    expect(previews[0]!.request.columns[0]!.default).toBeNull();
  });

  it("shows why the backend cannot build the statement, and clears it on a successful retry", async () => {
    previewError = { kind: "invalid_input", message: "Duplicate column name: id" };
    const { dialog } = renderDialog();
    fireEvent.change(screen.getByLabelText("Table name"), { target: { value: "orders" } });
    fireEvent.click(reviewButton());
    expect(await dialog.findByText("Duplicate column name: id")).toBeInTheDocument();
    expect(screen.queryByRole("dialog", { name: "Create table" })).not.toBeInTheDocument();

    previewError = null;
    await openReview();
    expect(dialog.queryByText("Duplicate column name: id")).not.toBeInTheDocument();
  });

  it("shows a failed create in the review and does not report the table as created", async () => {
    applyError = { kind: "database", message: 'relation "orders" already exists' };
    const { onCreated } = renderDialog();
    fireEvent.change(screen.getByLabelText("Table name"), { target: { value: "orders" } });
    const review = await openReview();
    fireEvent.click(within(review).getByRole("button", { name: "Create table" }));

    expect(await within(review).findByRole("alert")).toHaveTextContent('relation "orders" already exists');
    expect(onCreated).not.toHaveBeenCalled();
    expect(screen.queryByText(/Created/)).not.toBeInTheDocument();
  });

  it("returns to the form when the review is cancelled", async () => {
    const { onClose } = renderDialog();
    fireEvent.change(screen.getByLabelText("Table name"), { target: { value: "orders" } });
    const review = await openReview();
    fireEvent.click(within(review).getByRole("button", { name: "Cancel" }));
    expect(screen.queryByRole("dialog", { name: "Create table" })).not.toBeInTheDocument();
    expect(screen.getByLabelText("Table name")).toHaveValue("orders");
    expect(onClose).not.toHaveBeenCalled();
    expect(ddl).toEqual([]);
  });

  it("closes without sending anything on Cancel", () => {
    const { onClose, dialog } = renderDialog();
    fireEvent.change(screen.getByLabelText("Table name"), { target: { value: "orders" } });
    fireEvent.click(dialog.getByRole("button", { name: "Cancel" }));
    expect(onClose).toHaveBeenCalledTimes(1);
    expect(previews).toEqual([]);
  });
});
