import { useState } from "react";
import { Icon } from "../../components/Icon";
import type { ColumnDef, SessionInfo } from "../../types/backend";
import { api, toError } from "../../lib/ipc";
import { Dialog } from "../../components/Dialog";
import { ReviewChangesDialog } from "../data-browser/ReviewChangesDialog";
import { notify } from "../../stores/ui";

const TYPE_SUGGESTIONS: Record<string, string[]> = {
  postgres: ["bigint", "integer", "text", "varchar(255)", "boolean", "numeric(12,2)", "timestamptz", "date", "uuid", "jsonb", "bytea"],
  mysql: ["bigint", "int", "varchar(255)", "text", "tinyint(1)", "decimal(12,2)", "datetime", "date", "json", "blob"],
  sqlite: ["INTEGER", "TEXT", "REAL", "NUMERIC", "BLOB"],
  mssql: ["bigint", "int", "nvarchar(255)", "nvarchar(max)", "bit", "decimal(12,2)", "datetime2", "date", "uniqueidentifier", "varbinary(max)"],
};

export function CreateTableDialog({
  session,
  schema,
  onClose,
  onCreated,
}: {
  session: SessionInfo;
  schema: string;
  onClose: () => void;
  onCreated: (name: string) => void;
}) {
  const duck = session.server.product === "DuckDB";
  const idType = duck
    ? "BIGINT"
    : session.dialect === "postgres"
      ? "bigint GENERATED BY DEFAULT AS IDENTITY"
      : session.dialect === "mysql"
        ? "bigint AUTO_INCREMENT"
        : session.dialect === "mssql"
          ? "bigint IDENTITY"
          : "INTEGER";
  const [name, setName] = useState("");
  const [columns, setColumns] = useState<ColumnDef[]>([{ name: "id", dataType: idType, nullable: false, default: null, primaryKey: true }]);
  const [review, setReview] = useState<string[] | null>(null);
  const [error, setError] = useState<string | null>(null);
  const types = TYPE_SUGGESTIONS[session.dialect] ?? [];

  const set = (i: number, patch: Partial<ColumnDef>) => setColumns((c) => c.map((x, k) => (k === i ? { ...x, ...patch } : x)));

  const preview = async () => {
    setError(null);
    try {
      setReview(await api.previewCreateTable(session.sessionId, { schema, name: name.trim(), columns }));
    } catch (e) {
      setError(toError(e).message);
    }
  };

  return (
    <>
      <Dialog
        title={`New table in ${schema}`}
        wide
        onClose={onClose}
        footer={
          <>
            <button className="btn" onClick={onClose}>
              Cancel
            </button>
            <button className="btn btn-primary" onClick={preview} disabled={!name.trim() || columns.some((c) => !c.name.trim())}>
              Review SQL
            </button>
          </>
        }
      >
        <label className="field">
          <span>Table name</span>
          <input className="input" value={name} onChange={(e) => setName(e.target.value)} />
        </label>
        <datalist id="type-suggestions">
          {types.map((t) => (
            <option key={t} value={t} />
          ))}
        </datalist>
        <table className="table">
          <thead>
            <tr>
              <th>Column</th>
              <th>Type</th>
              <th>Default</th>
              <th>NULL</th>
              <th>Key</th>
              <th />
            </tr>
          </thead>
          <tbody>
            {columns.map((c, i) => (
              <tr key={i}>
                <td>
                  <input className="input" aria-label="Column name" value={c.name} onChange={(e) => set(i, { name: e.target.value })} />
                </td>
                <td>
                  <input className="input mono" aria-label="Type" list="type-suggestions" value={c.dataType} onChange={(e) => set(i, { dataType: e.target.value })} />
                </td>
                <td>
                  <input className="input mono" aria-label="Default" value={c.default ?? ""} onChange={(e) => set(i, { default: e.target.value || null })} />
                </td>
                <td>
                  <input type="checkbox" aria-label="Nullable" checked={c.nullable} onChange={(e) => set(i, { nullable: e.target.checked })} />
                </td>
                <td>
                  <input type="checkbox" aria-label="Primary key" checked={c.primaryKey} onChange={(e) => set(i, { primaryKey: e.target.checked, nullable: e.target.checked ? false : c.nullable })} />
                </td>
                <td>
                  <button className="btn btn-ghost btn-icon" aria-label="Remove column" onClick={() => setColumns((x) => x.filter((_, k) => k !== i))} disabled={columns.length === 1}>
                    <Icon name="delete" size={13} />
                  </button>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
        <div>
          <button className="btn" onClick={() => setColumns((c) => [...c, { name: "", dataType: types[2] ?? "text", nullable: true, default: null, primaryKey: false }])}>
            <Icon name="add" size={14} /> Add column
          </button>
        </div>
        {error && <div className="notice notice-error">{error}</div>}
      </Dialog>
      {review && (
        <ReviewChangesDialog
          session={session}
          title="Create table"
          sql={review.map((s) => `${s};`).join("\n\n")}
          atomic={session.capabilities.transactionalDdl}
          summary={`Creates ${schema}.${name}`}
          commitLabel="Create table"
          onClose={() => setReview(null)}
          onCommit={async () => {
            await api.applyDdl(session.sessionId, review);
            notify(`Created ${name}`, "success");
            onCreated(name.trim());
          }}
        />
      )}
    </>
  );
}
